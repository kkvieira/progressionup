  /** Recebe um texto JÁ ESCAPADO (ou HTML confiável) e devolve com os emojis trocados por ícones */
  function pxText(html) {
    return String(html ?? '').replace(emojiRe, m => {
      const key = m.replace(/️/g, '');
      if (MEDALS[key]) return `<span class="px-medal ${MEDALS[key]}">${pxIcon('medal')}</span>`;
      return pxIcon(EMOJI_MAP[key]);
    });
  }
  window.pxText = pxText;

  const cache = {};
  function buildSvg(name) {
    const rows = ICONS[name];
    if (!rows) return '';
    const h = rows.length;
    const w = Math.max(...rows.map(r => r.length));
    const size = Math.max(w, h);
    const ox = Math.floor((size - w) / 2), oy = Math.floor((size - h) / 2);
    let main = '', alt = '';
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const ch = row[x];
        if (ch === '#' || ch === 'o') {
          let len = 1;
          while (row[x + len] === ch) len++;
          const d = `M${x + ox} ${y + oy}h${len}v1h-${len}z`;
          if (ch === '#') main += d; else alt += d;
          x += len;
        } else x++;
      }
    });
    return `<svg class="px-ico" viewBox="0 0 ${size} ${size}" aria-hidden="true" focusable="false" shape-rendering="crispEdges">` +
      `<path fill="currentColor" d="${main}"/>` +
      (alt ? `<path class="px-alt" d="${alt}"/>` : '') +
      `</svg>`;
  }

  function pxIcon(name) {
    if (!(name in cache)) cache[name] = buildSvg(name);
    return cache[name];
  }

  function hydrate(root) {
    const scope = root && root.querySelectorAll ? root : document;
    const list = scope.querySelectorAll ? scope.querySelectorAll('i[data-ico]:not([data-ico-done])') : [];
    list.forEach(el => {
      el.innerHTML = pxIcon(el.dataset.ico);
      el.setAttribute('data-ico-done', '');
      el.classList.add('px-ico-wrap');
    });
    if (root && root.matches && root.matches('i[data-ico]:not([data-ico-done])')) hydrate(root.parentNode);
  }

  window.PX_ICONS = ICONS;
  window.pxIcon = pxIcon;
  window.hydratePxIcons = hydrate;

  const start = () => {
    hydrate(document);
    // Conteúdo criado depois (listas, modais, loja) também recebe os ícones
    new MutationObserver(muts => {
      for (const m of muts) m.addedNodes.forEach(n => { if (n.nodeType === 1) hydrate(n); });
    }).observe(document.body, { childList: true, subtree: true });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
